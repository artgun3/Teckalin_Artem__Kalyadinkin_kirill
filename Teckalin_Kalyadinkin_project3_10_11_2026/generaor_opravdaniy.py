import random
import tkinter as tk

# 1. Создаем главное окно (в самом начале программы!)
root = tk.Tk()
root.title("Генератор отговорок")

# Список отговорок
excuses = ["Застрял в лифте", "У меня лапки", "Кот уснул на клавиатуре", "На мою машину напали инопланетяне, пришлось давать показания.", "Я помог кошачьему приюту поймать сбежавшего енота.", "Мой будильник решил, что сегодня суббота, и я не стал с ним спорить.", "Пуговку на рубашке пришлось пришивать три раза — она сопротивлялась.", "Мне дорогу перебежал черный кот, пришлось обходить через другой район."]


def show_excuse():
    # Выбираем случайную отговорку
    random_excuse = random.choice(excuses)
    # ПРАВИЛЬНО: Обновляем текст в метке
    label_result.config(text=random_excuse)


# 2. Создаем виджеты
label_result = tk.Label(root, text="Нажмите кнопку, чтобы получить отговорку")
label_result.pack(pady=10)

btn = tk.Button(root, text="Получить", command=show_excuse)
btn.pack(pady=10)

root.mainloop()